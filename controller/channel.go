// validateChannelConfig rejects a channel config that names an upstream
// protocol the gateway does not know. Without this a typo would silently
// resolve to openai-chat, which takes the translation path and drops the native
// fields (cache_control, thinking, hosted tools) that same-protocol passthrough
// exists to preserve — a failure with no error anywhere.
func validateChannelConfig(configJSON string) error {
	if strings.TrimSpace(configJSON) == "" {
		return nil
	}
	var cfg model.ChannelConfig
	if err := json.Unmarshal([]byte(configJSON), &cfg); err != nil {
		return fmt.Errorf("渠道配置不是合法的 JSON：%s", err.Error())
	}
	if cfg.UpstreamProtocol != "" && !upstream.Valid(cfg.UpstreamProtocol) {
		return fmt.Errorf("未知的上游协议 %q，可选值：openai-chat / openai-responses / anthropic-messages / compatible",
			cfg.UpstreamProtocol)
	}
	if !relaymodel.ValidToolLossPolicy(cfg.ToolLossPolicy) {
		return fmt.Errorf("未知的托管工具丢损策略 %q，可选值：allow / safe / strict", cfg.ToolLossPolicy)
	}
	return nil
}

func GetAllChannels(c *gin.Context) {
	p, _ := strconv.Atoi(c.Query("p"))
	if p < 0 {
		p = 0
	}
	channels, err := model.GetAllChannels(p*config.ItemsPerPage, config.ItemsPerPage, "limited")
	if err != nil {
		c.JSON(http.StatusOK, gin.H{
			"success": false,
			"message": err.Error(),
		})
		return
	}
	c.JSON(http.StatusOK, gin.H{
		"success": true,
		"message": "",
		"data":    channels,
	})
	return
}

